def lab(lrgb):
    r, g, b = (max(0.0, min(1.0, x)) for x in lrgb)
    x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
    f = lambda t: t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116
    return 116 * f(y) - 16, 500 * (f(x) - f(y)), 200 * (f(y) - f(z))


def de2000(l1, l2):
    L1, a1, b1 = l1
    L2, a2, b2 = l2
    C1, C2 = math.hypot(a1, b1), math.hypot(a2, b2)
    Cm = (C1 + C2) / 2
    G = 0.5 * (1 - math.sqrt(Cm ** 7 / (Cm ** 7 + 25 ** 7)))
    a1p, a2p = (1 + G) * a1, (1 + G) * a2
    C1p, C2p = math.hypot(a1p, b1), math.hypot(a2p, b2)
    h1p, h2p = math.degrees(math.atan2(b1, a1p)) % 360, math.degrees(math.atan2(b2, a2p)) % 360
    dL, dC = L2 - L1, C2p - C1p
    dh = 0 if C1p * C2p == 0 else (h2p - h1p if abs(h2p - h1p) <= 180 else h2p - h1p - 360 if h2p > h1p else h2p - h1p + 360)
    dH = 2 * math.sqrt(C1p * C2p) * math.sin(math.radians(dh / 2))
    Lm, Cmp = (L1 + L2) / 2, (C1p + C2p) / 2
    hm = h1p + h2p if C1p * C2p == 0 else ((h1p + h2p) / 2 if abs(h1p - h2p) <= 180 else (h1p + h2p + 360) / 2 if h1p + h2p < 360 else (h1p + h2p - 360) / 2)
    T = 1 - 0.17 * math.cos(math.radians(hm - 30)) + 0.24 * math.cos(math.radians(2 * hm)) + 0.32 * math.cos(math.radians(3 * hm + 6)) - 0.20 * math.cos(math.radians(4 * hm - 63))
    SL = 1 + 0.015 * (Lm - 50) ** 2 / math.sqrt(20 + (Lm - 50) ** 2)
    SC, SH = 1 + 0.045 * Cmp, 1 + 0.015 * Cmp * T
    RT = -2 * math.sqrt(Cmp ** 7 / (Cmp ** 7 + 25 ** 7)) * math.sin(math.radians(60 * math.exp(-((hm - 275) / 25) ** 2)))
    return math.sqrt((dL / SL) ** 2 + (dC / SC) ** 2 + (dH / SH) ** 2 + RT * (dC / SC) * (dH / SH))


def delta_e(a, b, kind=None):
    la, lb = [lin(x) for x in rgb(a)], [lin(x) for x in rgb(b)]
    if kind:
        m = CVD[kind]
        la, lb = [sum(m[i][j] * la[j] for j in range(3)) for i in range(3)], [sum(m[i][j] * lb[j] for j in range(3)) for i in range(3)]
    return round(de2000(lab(la), lab(lb)), 1)


def cvd(name, *, title, target, date, summary, palette, pairs, confuse, issues, fixes=None, standard="WCAG 2.2 AA"):
    contrasts = []
    for fg, bg, where, large in pairs:
        need = 3.0 if large else 4.5
        r = contrast(fg, bg)
        contrasts.append({"where": where, "fg": fg, "bg": bg, "ratio": r, "required": need, "pass": r >= need})
    confusions = []
    for a, b, where in confuse:
        d = {"where": where, "colors": [a, b], "normal": delta_e(a, b)}
        for k in CVD:
            d[k] = delta_e(a, b, k)
        d["affected"] = [k for k in CVD if d[k] < 12]
        confusions.append(d)
    by_type = [{"type": k, "issues": sum(1 for i in issues if k in i["affects"])} for k in CVD]
    failing = sum(1 for c in contrasts if not c["pass"])
    colour_only = any(i["type"] == "仅靠颜色" and i["severity"] == "高" for i in issues)
    verdict = "不友好" if colour_only or sum(1 for c in confusions if c["affected"]) >= 2 else "基本友好" if confusions and any(c["affected"] for c in confusions) or failing else "友好"
    d = {
        "title": title, "target": target, "date": date, "standard": standard, "verdict": verdict,
        "method": "按 Machado 2009 模型模拟红色盲、绿色盲、蓝色盲;色差为 CIEDE2000 ΔE,小于 12 视为难以区分",
        "summary": summary,
        # The interface as checked, and as seen with each colour blindness (simulate_cvd.py).
        "screens": [{"view": "原界面", "image": "assets/original.png"}] + [{"view": k, "image": f"assets/{SIM[k]}.png"} for k in CVD],
        "kpis": [
            {"key": "pairs", "label": "检查的文字与背景组合", "value": len(contrasts), "unit": "组"},
            {"key": "fail", "label": "对比度不达标", "value": failing, "unit": "组"},
            {"key": "confuse", "label": "色盲用户难以区分的颜色", "value": sum(1 for c in confusions if c["affected"]), "unit": "对"},
            {"key": "issues", "label": "问题总数", "value": len(issues), "unit": "个"},
        ],
        "palette": palette,
        "contrast": contrasts,
        "confusions": confusions,
        "byType": by_type,
        "issues": issues,
    }
    if fixes:
        d["fixes"] = [{**f, "before": contrast(f["from"], f["bg"]), "after": contrast(f["to"], f["bg"])} for f in fixes]
    save("cvd", name, d)


