"""Sample outputs of the two pilot Skills, 6 each (made up, but internally consistent).

    python3 skills/make_data.py

交互流程挖掘 (flow): one task (e.g. opening a bank account online), the screen-by-screen chain
of 2-4 products doing it; each screen is analysed, then the products are compared stage by
stage, with common patterns, issues and suggestions. Product names are made up.
色觉无障碍分析 (cvd): whether an interface works for colour-blind users — palette, WCAG
contrast of text/background pairs, colour pairs that colour-blind users cannot tell apart,
issues and fixes. Contrast ratios and the colour
differences under simulated colour blindness are computed, not typed in.

Samples 1-4 are for training, 5-6 are held out (see split.json).
Images live in data/<sample>/ and are referenced as assets/<file> (the generator copies the
folder into the workspace as assets/): make_images.mjs draws them, simulate_cvd.py adds the
colour-blind views.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).parent


def save(skill, name, data):
    d = ROOT / skill / "data"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{name}.json").write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n")


# ---------------------------------------------------------------- 交互流程挖掘

def chain(product, version, verdict, *steps):
    """steps: (screen, what is on it, the action that moves on, fields to fill, note)."""
    return {
        "product": product, "version": version, "verdict": verdict,
        "steps": [{"no": i + 1, "screen": s, "content": c, "action": a, "inputs": n, "note": t}
                  for i, (s, c, a, n, t) in enumerate(steps)],
    }


def flow(name, *, title, task, scope, date, summary, chains, issues, suggestions, stages=None, patterns=None):
    # Each screen's screenshot: assets/p<product>-<step>.png (drawn by make_images.mjs).
    for pi, c in enumerate(chains):
        for st in c["steps"]:
            st["image"] = f"assets/p{pi + 1}-{st['no']:02d}.png"
    n = [len(c["steps"]) for c in chains]
    products = [{"name": c["product"], "steps": len(c["steps"]), "inputs": sum(s["inputs"] for s in c["steps"]), "verdict": c["verdict"]} for c in chains]
    fewest = min(products, key=lambda p: p["steps"])
    d = {
        "title": title, "task": task, "scope": scope, "date": date, "summary": summary,
        "kpis": [
            {"key": "products", "label": "对比产品", "value": len(chains), "unit": "个"},
            {"key": "screens", "label": "分析截图", "value": sum(n), "unit": "张"},
            {"key": "fewest", "label": f"步骤最少({fewest['name']})", "value": fewest["steps"], "unit": "步"},
            {"key": "issues", "label": "发现问题", "value": len(issues), "unit": "个"},
        ],
        "products": products,
        "chains": chains,
    }
    if stages:
        d["stages"] = stages
    if patterns:
        d["patterns"] = patterns
    d["issues"] = issues
    d["suggestions"] = suggestions
    save("flow", name, d)


def iss(i, product, step, title, severity, evidence):
    return {"id": i, "product": product, "step": step, "title": title, "severity": severity, "evidence": evidence}


def sug(i, title, detail, basis):
    return {"id": i, "title": title, "detail": detail, "basis": basis}


